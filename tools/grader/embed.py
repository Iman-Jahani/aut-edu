"""Regenerates src/lib/graderHarness.ts from main.py / runner.py.   python3 tools/grader/embed.py"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "src", "lib", "graderHarness.ts")

def lit(name):
    src = open(os.path.join(HERE, name), encoding="utf-8").read()
    assert "`" not in src and "${" not in src, name + " must not contain backticks or ${"
    return src

ts = '''// GENERATED by tools/grader/embed.py from tools/grader/main.py + runner.py — edit those, then re-run the script.
// Python harness that grades a submission on the remote executor (see /api/grade). Tested with tools/grader/test_grader.py.
import type { RunnerFile } from "@/lib/serverRunCore";

const GRADER_MAIN = String.raw`%s`;

const GRADER_RUNNER = String.raw`%s`;

/** One test as understood by the Python grader. */
export interface GradeTest {
  kind: "exact" | "checker";
  input: string;
  expected: string;
  hidden?: boolean;
  /** "seed: 7\\nrandint: 4, 2\\nchoice: 0\\nrandom: 0.5" */
  random?: string;
  checker?: string;
  runs?: number;
}

export interface GradeResultRaw {
  id: number;
  kind: "exact" | "checker";
  hidden: boolean;
  passed: boolean;
  input: string;
  expected: string;
  actual: string;
  error: string | null;
  message: string;
  runs: number;
  runs_passed: number;
}

/** spec.json is deleted by main.py before any student code runs, so hidden tests/checkers can't be read by it. */
export function buildGradeFiles(code: string, tests: GradeTest[], opts: { timeout?: number; budget?: number } = {}): RunnerFile[] {
  return [
    { name: "main.py", content: GRADER_MAIN },
    { name: "runner.py", content: GRADER_RUNNER },
    { name: "student.py", content: code },
    { name: "spec.json", content: JSON.stringify({ tests, timeout: opts.timeout ?? 3, budget: opts.budget ?? 30 }) },
  ];
}
''' % (lit("main.py"), lit("runner.py"))
open(OUT, "w", encoding="utf-8").write(ts)
print("wrote", OUT)
